-- The only way a run gets into the table. It checks that the run is one the day's Daily Game could
-- have produced, stores it (once per run id) and returns its place in its day.
create or replace function public.submit_run(
  p_run_id        uuid,
  p_day           date,
  p_campaign      text,
  p_empire_name   text,
  p_flag_pattern  integer,
  p_flag_colours  text[],
  p_start_country text,
  p_score         numeric,
  p_conquered     integer,
  p_continents    integer,
  p_battles       integer,
  p_best_streak   integer,
  p_outcome       text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  -- The Daily Game is a World conquest: every country, and six continents to hold.
  v_countries  constant integer := 230;
  v_continents constant integer := 6;
  v_name       text;
  v_run        public.runs%rowtype;
  v_rank       integer;
begin
  if p_run_id is null or p_day is null or p_campaign is null or p_empire_name is null or p_flag_pattern is null or p_flag_colours is null
     or p_start_country is null or p_score is null or p_conquered is null or p_continents is null or p_battles is null
     or p_best_streak is null or p_outcome is null then
    raise exception 'A run needs every field.';
  end if;

  -- Only today's game counts, or yesterday's for a run that was still being played at midnight.
  if p_day not between public.atlas_today() - 1 and public.atlas_today() then
    raise exception 'That daily game is over.';
  end if;
  if p_campaign <> 'World' then
    raise exception 'The daily game is a World conquest.';
  end if;
  -- Everyone starts the day from the same country.
  if p_start_country is distinct from public.atlas_daily_country(p_day) then
    raise exception 'That is not the starting country of the day.';
  end if;

  -- The empire's name: letters, apostrophes and single spaces, 3 to 24 characters, and the name rules.
  v_name := btrim(regexp_replace(translate(p_empire_name, '‘’', ''''''), '\s+', ' ', 'g'));
  if not public.atlas_name_allowed(v_name) then
    raise exception 'That empire name is not allowed.';
  end if;

  -- The flag: one of the game's sixteen patterns, in three colours from its palette.
  if p_flag_pattern not between 0 and 15 then
    raise exception 'Unknown flag pattern.';
  end if;
  if array_ndims(p_flag_colours) is distinct from 1 or array_length(p_flag_colours, 1) is distinct from 3
     or not (p_flag_colours <@ array['#f4f4ec', '#1b1f33', '#d8343c', '#ef7d2e', '#ffcd3c', '#2fa84f', '#1fa2a0', '#5fb3f2', '#2b4fc4', '#7b3fb5', '#f078b4', '#8a5a3b']) then
    raise exception 'Flag colours must be three colours from the palette.';
  end if;

  if p_outcome not in ('victory', 'defeat') then
    raise exception 'Unknown outcome.';
  end if;

  -- The starting country is given, not conquered, so the most there is to conquer is one fewer.
  if p_conquered not between 0 and v_countries - 1 then
    raise exception 'More countries conquered than there are.';
  end if;
  -- A victory is every country; anything less is a defeat.
  if (p_outcome = 'victory') <> (p_conquered = v_countries - 1) then
    raise exception 'The outcome does not match the countries conquered.';
  end if;
  -- Holding every continent is the same thing as winning.
  if p_continents not between 0 and v_continents or (p_outcome = 'victory') <> (p_continents = v_continents) then
    raise exception 'The continents held do not match the outcome.';
  end if;

  -- The score is one point per country conquered + 10 per continent: the daily start carries no
  -- multiplier, since everyone has the same one.
  if p_score <> p_conquered + p_continents * 10 then
    raise exception 'The score does not add up.';
  end if;

  -- Every conquest takes a battle. (A defeat need not be one more: a player may give up between battles.)
  if p_battles < p_conquered or p_battles > 100000 then
    raise exception 'The battles fought do not match the countries conquered.';
  end if;
  -- A conquest ends on a right answer, so it leaves a streak of at least one.
  if p_best_streak not between 0 and 100000 or (p_conquered > 0 and p_best_streak < 1) then
    raise exception 'The best streak does not match the countries conquered.';
  end if;

  -- One row per run id: sending a run again changes nothing and returns the same place.
  insert into public.runs (run_id, day, campaign, empire_name, flag_pattern, flag_colours, start_country, score, conquered, continents, battles, best_streak, outcome)
  values (p_run_id, p_day, p_campaign, v_name, p_flag_pattern, p_flag_colours, p_start_country, p_score, p_conquered, p_continents, p_battles, p_best_streak, p_outcome)
  on conflict (run_id) do nothing;

  select r.* into v_run from public.runs r where r.run_id = p_run_id;

  -- Its place: one more than the number of runs that day that rank above it.
  select count(*) + 1 into v_rank
  from public.runs r
  where r.day = v_run.day
    and (r.score > v_run.score
      or (r.score = v_run.score and (r.battles < v_run.battles
        or (r.battles = v_run.battles and (r.created_at < v_run.created_at
          or (r.created_at = v_run.created_at and r.run_id < v_run.run_id))))));
  return v_rank;
end;
$$;

-- ------------------------------------------------------------------ reading the leaderboard

-- The best runs of a day (today when p_day is null), best first.
create or replace function public.top_runs(p_day date default null, p_limit integer default 5)
returns table (
  rank          bigint,
  run_id        uuid,
  day           date,
  campaign      text,
  empire_name   text,
  flag_pattern  smallint,
  flag_colours  text[],
  start_country text,
  score         numeric,
  conquered     smallint,
  continents    smallint,
  battles       integer,
  best_streak   integer,
  outcome       text,
  created_at    timestamptz
)
language sql
stable
set search_path = ''
as $$
  select ranked.place, ranked.run_id, ranked.day, ranked.campaign, ranked.empire_name, ranked.flag_pattern, ranked.flag_colours,
         ranked.start_country, ranked.score, ranked.conquered, ranked.continents, ranked.battles, ranked.best_streak,
         ranked.outcome, ranked.created_at
  from (
    select r.*, row_number() over (order by r.score desc, r.battles asc, r.created_at asc, r.run_id asc) as place
    from public.runs r
    where r.day = coalesce(p_day, public.atlas_today())
  ) as ranked
  where ranked.place <= least(greatest(coalesce(p_limit, 5), 1), 50)
  order by ranked.place;
$$;

-- How many players finished a day (today when p_day is null) on each score, lowest first: the spread
-- a player's own score is set against.
create or replace function public.day_scores(p_day date default null)
returns table (score numeric, players bigint)
language sql
stable
set search_path = ''
as $$
  select r.score, count(*) as players
  from public.runs r
  where r.day = coalesce(p_day, public.atlas_today())
  group by r.score
  order by r.score;
$$;

