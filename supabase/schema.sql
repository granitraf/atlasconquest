-- Atlas Conquest: the daily leaderboard.
--
-- Run this whole file once in the Supabase dashboard: SQL editor > New query > paste > Run.
-- It is safe to run again: it creates what is missing and replaces the functions.
--
-- What it sets up:
--   * one table, public.runs: one row per finished Daily Game, nothing that identifies a player;
--   * anyone may READ it (the page's public key included);
--   * nobody may insert, update or delete rows directly. A run gets in through one door only,
--     the function submit_run, which checks everything it is told before it stores a row;
--   * top_runs, which returns the best runs of a day in ranking order;
--   * day_scores, which returns how many players finished a day on each score.
--
-- The Daily Game: one starting country a day, the same for every player, changing at midnight
-- US Eastern time. The leaderboard starts afresh each day.
--
-- The numbers in here (the countries, the daily order, the flag palette, the name rules) mirror the
-- game's own. tests/leaderboard.test.ts, tests/empireName.test.ts and tests/daily.test.ts fail if they drift.

-- ------------------------------------------------------------------ the table

create table if not exists public.runs (
  run_id        uuid         primary key,
  campaign      text         not null check (campaign in ('World', 'Africa', 'Asia', 'Europe', 'North America', 'South America', 'Oceania')),
  empire_name   text         not null,
  flag_pattern  smallint     not null check (flag_pattern between 0 and 15),
  flag_colours  text[]       not null check (array_length(flag_colours, 1) = 3),
  start_country text         not null check (start_country ~ '^[A-Z]{3}$'),
  score         numeric(7,1) not null check (score >= 0),
  conquered     smallint     not null check (conquered >= 0),
  continents    smallint     not null check (continents >= 0),
  battles       integer      not null check (battles >= 0),
  best_streak   integer      not null check (best_streak >= 0),
  outcome       text         not null check (outcome in ('victory', 'defeat')),
  -- Set by the database, never by the player, so a run cannot be back-dated to win a tie.
  created_at    timestamptz  not null default now()
);

-- The day (US Eastern) a run is the Daily Game for. Added here rather than declared in the table, so
-- running this file again updates a table made by an earlier version. Rows from before the Daily Game
-- have no day and appear on no leaderboard.
alter table public.runs add column if not exists day date;

-- Empire names: letters, apostrophes inside or at the end of a word, and single spaces, 3 to 24
-- characters. (Replaced rather than declared in the table, for the same reason. Rows already stored are
-- left alone; the game hides any stored name that no longer passes.)
alter table public.runs drop constraint if exists runs_empire_name_check;
alter table public.runs add constraint runs_empire_name_check
  check (char_length(empire_name) between 3 and 24 and empire_name ~ '^[A-Za-z]+(''[A-Za-z]+)*''?( [A-Za-z]+(''[A-Za-z]+)*''?)*$') not valid;

-- The ranking order within a day: best score first, then fewer battles, then the earlier run.
drop index if exists public.runs_ranking;
create index if not exists runs_daily on public.runs (day, score desc, battles, created_at, run_id);

-- ------------------------------------------------------------------ who may do what

alter table public.runs enable row level security;

drop policy if exists "Anyone may read the leaderboard" on public.runs;
create policy "Anyone may read the leaderboard" on public.runs
  for select to anon, authenticated using (true);

-- No policy allows insert, update or delete, so row level security refuses all three.
-- The table privileges say the same thing a second time.
revoke all on table public.runs from anon, authenticated;
grant select on table public.runs to anon, authenticated;

