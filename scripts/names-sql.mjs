// Copies the empire name rules into the database: rewrites the function atlas_name_allowed in
// supabase/schema.sql from src/names/blocked-names.json and src/names/allowed-names.json.
//   npm run names           then re-run supabase/schema.sql in the Supabase SQL editor.
//   npm run names -- --check   exits 1 if schema.sql is out of date (used by the tests).
//
// The database repeats the format rules and the custom blocklist and allowlist. It cannot run the
// obscenity library, so names the library alone refuses are refused by the game but not by the database.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = join(root, 'supabase', 'schema.sql');
const START = '-- >>> name rules: generated by `npm run names` from src/names/*.json. Do not edit by hand.';
const END = '-- <<< name rules';
/** NAME_FORMAT in src/names/validateEmpireName.ts, quoted for SQL. */
export const SQL_FORMAT = "^[A-Za-z]+(''[A-Za-z]+)*''?( [A-Za-z]+(''[A-Za-z]+)*''?)*$";

/** Mirrors ALLOWED_PATTERN and BLOCKED_PATTERN in src/names/validateEmpireName.ts. */
export function namePatterns() {
  const read = (file) => JSON.parse(readFileSync(join(root, 'src', 'names', file), 'utf8'));
  const blocked = read('blocked-names.json').blocked;
  const allowed = read('allowed-names.json').allowed;
  for (const term of blocked) if (!/^[a-z]+$/.test(term)) throw new Error(`blocked-names.json: "${term}" must be lower-case letters only`);
  for (const name of allowed) if (!/^[a-z]+( [a-z]+)*$/.test(name)) throw new Error(`allowed-names.json: "${name}" must be lower-case letters and single spaces`);
  const byLength = (list) => [...list].sort((a, b) => b.length - a.length || a.localeCompare(b));
  return { allowed: ` (${byLength(allowed).join('|')})(?= )`, blocked: `(${byLength(blocked).join('|')})` };
}

export function nameFunction() {
  const { allowed, blocked } = namePatterns();
  return `${START}
-- The format rules and the custom blocklist and allowlist, as validateEmpireName applies them in the game.
create or replace function public.atlas_name_allowed(p_name text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $fn$
declare
  v_typed  text;
  v_joined text;
begin
  if p_name is null then
    return false;
  end if;
  -- Letters, apostrophes inside or at the end of a word, and single spaces; 3 to 24 characters.
  v_typed := btrim(regexp_replace(translate(p_name, '\u2018\u2019', ''''''), '\\s+', ' ', 'g'));
  if v_typed !~ '${SQL_FORMAT}' or char_length(v_typed) not between 3 and 24 then
    return false;
  end if;
  -- Apostrophes ignored and allowlisted words out, then the name as typed, with the spaces taken out,
  -- and with letters repeated three or more times squeezed to one and to two.
  v_typed := btrim(regexp_replace(' ' || replace(lower(v_typed), '''', '') || ' ', '${allowed}', ' ', 'g'));
  v_joined := replace(v_typed, ' ', '');
  return not (v_typed ~ '${blocked}'
    or v_joined ~ '${blocked}'
    or regexp_replace(v_joined, '(.)\\1\\1+', '\\1', 'g') ~ '${blocked}'
    or regexp_replace(v_joined, '(.)\\1\\1+', '\\1\\1', 'g') ~ '${blocked}');
end;
$fn$;
${END}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const schema = readFileSync(SCHEMA, 'utf8');
  const from = schema.indexOf(START);
  const to = schema.indexOf(END);
  if (from === -1 || to === -1) throw new Error('supabase/schema.sql has no generated name rules section');
  const next = schema.slice(0, from) + nameFunction() + schema.slice(to + END.length);
  if (process.argv.includes('--check')) {
    if (next !== schema) {
      console.error('supabase/schema.sql is out of date: run `npm run names`.');
      process.exit(1);
    }
    console.log('supabase/schema.sql matches the name lists.');
  } else {
    writeFileSync(SCHEMA, next);
    const { blocked, allowed } = { blocked: namePatterns().blocked.split('|').length, allowed: namePatterns().allowed.split('|').length };
    console.log(`Wrote the name rules into supabase/schema.sql: ${blocked} blocked terms, ${allowed} allowed names.`);
    console.log('Now re-run supabase/schema.sql in the Supabase SQL editor.');
  }
}
