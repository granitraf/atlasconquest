// Copies the Daily Game's order of countries into the database: rewrites the function atlas_daily_country in
// supabase/schema.sql from config/daily-order.json, so the database can check that a run really started
// from the country of its day.
//   npm run daily             then re-run supabase/schema.sql in the Supabase SQL editor.
//   npm run daily -- --check  exits 1 if schema.sql is out of date (used by the tests).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = join(root, 'supabase', 'schema.sql');
const START = '-- >>> daily order: generated by `npm run daily` from config/daily-order.json. Do not edit by hand.';
const END = '-- <<< daily order';

export function dailyFunction() {
  const { epoch, order } = JSON.parse(readFileSync(join(root, 'config', 'daily-order.json'), 'utf8'));
  if (!/^\d{4}-\d{2}-\d{2}$/.test(epoch)) throw new Error('config/daily-order.json: epoch must be YYYY-MM-DD');
  for (const id of order) if (!/^[A-Z]{3}$/.test(id)) throw new Error(`config/daily-order.json: bad country id "${id}"`);
  if (new Set(order).size !== order.length) throw new Error('config/daily-order.json: a country is listed twice');
  const n = order.length;
  const rows = [];
  for (let i = 0; i < n; i += 20) rows.push('    ' + order.slice(i, i + 20).map((id) => `'${id}'`).join(', '));
  return `${START}
-- The starting country of a day: day 0 is ${epoch}; each day takes the next of the ${n} countries, and the
-- list starts over after the last.
create or replace function public.atlas_daily_country(p_day date)
returns text
language sql
immutable
set search_path = ''
as $fn$
  select (array[
${rows.join(',\n')}
  ])[(((p_day - date '${epoch}') % ${n}) + ${n}) % ${n} + 1];
$fn$;
${END}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const schema = readFileSync(SCHEMA, 'utf8');
  const from = schema.indexOf(START);
  const to = schema.indexOf(END);
  if (from === -1 || to === -1) throw new Error('supabase/schema.sql has no generated daily order section');
  const next = schema.slice(0, from) + dailyFunction() + schema.slice(to + END.length);
  if (process.argv.includes('--check')) {
    if (next !== schema) {
      console.error('supabase/schema.sql is out of date: run `npm run daily`.');
      process.exit(1);
    }
    console.log('supabase/schema.sql matches the daily order.');
  } else {
    writeFileSync(SCHEMA, next);
    console.log('Wrote the daily order into supabase/schema.sql. Now re-run supabase/schema.sql in the Supabase SQL editor.');
  }
}
